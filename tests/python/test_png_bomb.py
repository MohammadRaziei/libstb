"""A tiny, valid PNG that declares an enormous image is refused from its header.

The decoder must answer with LimitError (not crash, not DecodeError, not an out-of-memory kill)
before allocating a single pixel. The file is generated by pngbomb.py; nothing large is committed.
"""

import time
import zlib

import pytest

import libstb as stb
import pngbomb


@pytest.fixture(scope="module")
def bomb():
    return pngbomb.make_bomb()


def test_the_bomb_is_a_real_png_and_really_is_small(bomb):
    assert len(bomb) < 2 * 1024 * 1024                       # a file you would happily accept...
    assert pngbomb.DECODED_BYTES > 512 * 1024 * 1024         # ...that decodes past the default limit
    assert pngbomb.DECODED_BYTES / len(bomb) > 500           # the ratio is the whole point

    # The pixel stream is complete and valid: it inflates to exactly what the header promises.
    idat = bomb[bomb.index(b"IDAT") + 4:bomb.index(b"IEND") - 8]
    inflater, total = zlib.decompressobj(), 0
    for i in range(0, len(idat), 65536):
        total += len(inflater.decompress(idat[i:i + 65536]))
    total += len(inflater.flush())
    assert total == pngbomb.scanline_stream_size(pngbomb.WIDTH, pngbomb.HEIGHT, pngbomb.CHANNELS)


def test_reading_only_the_header_is_fine_and_cheap(bomb):
    info = stb.ImageInfo.read(bomb)
    assert (info.width, info.height, info.channels) == (pngbomb.WIDTH, pngbomb.HEIGHT, pngbomb.CHANNELS)


def test_decoding_the_bomb_raises_limit_error_not_a_crash(bomb):
    with pytest.raises(stb.LimitError, match="too large"):
        stb.Image.open(bomb)
    with pytest.raises(stb.LimitError, match="too large"):
        stb.imread(bomb)
    # It is the size guard speaking, not the decoder giving up on a bad file:
    with pytest.raises(stb.Error) as e:
        stb.Image.open(bomb)
    assert type(e.value) is stb.LimitError and not isinstance(e.value, stb.DecodeError)


def test_the_refusal_is_quick(bomb):
    """It must not inflate 576 MB to find out: reading the header takes microseconds."""
    start = time.perf_counter()
    for _ in range(20):
        with pytest.raises(stb.LimitError):
            stb.Image.open(bomb)
    assert time.perf_counter() - start < 1.0


def test_the_same_construction_decodes_when_it_is_small(bomb):
    """Control: the limit is what stops the bomb, not a flaw in how the file is built."""
    small = pngbomb.make_png(64, 48, channels=4)
    img = stb.Image.open(small)
    assert (img.width, img.height, img.channels) == (64, 48, 4)
    assert img.tobytes() == bytes(64 * 48 * 4)


def test_a_lower_limit_stops_ordinary_sized_images_too():
    png = pngbomb.make_png(1000, 1000, channels=3)           # 3 MB decoded
    assert stb.Image.open(png).width == 1000
    with pytest.raises(stb.LimitError):
        stb.Image.open(png, max_bytes=1_000_000)
